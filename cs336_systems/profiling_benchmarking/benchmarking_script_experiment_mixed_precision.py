from pathlib import Path

import modal
import torch

from cs336_systems.profiling_benchmarking.benchmarking_script import (
    GPU,
    benchmark_method,
    configure_fp32_precision,
    get_random_batch,
    image,
)
from cs336_systems.profiling_benchmarking.benchmarking_script_experiment_1 import (
    BATCH_SIZE,
    MODEL_SIZES,
    TIMED_STEPS,
    WARMUP_STEPS,
    initialize_model_from_config,
    mean_and_std,
)

app = modal.App("cs336-systems-benchmarking-mixed-precision")
RESULTS_PATH = Path("tables/benchmarking_mixed_precision.tex")
TimingSummary = tuple[float | None, float | None]


def benchmark_model_precision(config: dict, *, use_bf16_autocast: bool) -> dict[str, TimingSummary]:
    batch = get_random_batch(
        batch_size=BATCH_SIZE,
        vocab_size=config["vocab_size"],
        context_length=config["context_length"],
    ).cuda()

    model = initialize_model_from_config(config)
    optimizer = torch.optim.AdamW(model.parameters())
    try:
        forward_times = benchmark_method(
            model,
            batch,
            "f",
            optimizer,
            WARMUP_STEPS,
            TIMED_STEPS,
            use_bf16_autocast=use_bf16_autocast,
        )
        forward_backward_times = benchmark_method(
            model,
            batch,
            "fb",
            optimizer,
            WARMUP_STEPS,
            TIMED_STEPS,
            use_bf16_autocast=use_bf16_autocast,
        )
    except torch.OutOfMemoryError:
        print(f"OOM config={config['name']} use_bf16_autocast={use_bf16_autocast}")
        return {"forward": (None, None), "backward": (None, None)}
    finally:
        del model
        del optimizer
        torch.cuda.empty_cache()

    backward_times = [fb_time - f_time for fb_time, f_time in zip(forward_backward_times, forward_times)]
    return {
        "forward": mean_and_std(forward_times),
        "backward": mean_and_std(backward_times),
    }


def benchmark_model_both_precisions(config: dict) -> dict[str, dict[str, TimingSummary]]:
    return {
        "fp32": benchmark_model_precision(config, use_bf16_autocast=False),
        "bf16": benchmark_model_precision(config, use_bf16_autocast=True),
    }


@app.function(image=image, gpu=GPU, timeout=7200)
def run_experiment_remote() -> dict[str, dict[str, dict[str, TimingSummary]]]:
    configure_fp32_precision()
    results: dict[str, dict[str, dict[str, TimingSummary]]] = {}
    for config in MODEL_SIZES:
        print(f"=== {config['name']} ===")
        results[config["name"]] = benchmark_model_both_precisions(config)
    return results


def format_mean_std_pair(summary: TimingSummary) -> tuple[str, str]:
    mean_value, std_value = summary
    if mean_value is None:
        return "OOM", "OOM"
    std_str = f"{std_value:.6f}" if std_value is not None else "0.000000"
    return f"{mean_value:.6f}", std_str


def write_latex_table(results: dict[str, dict[str, dict[str, TimingSummary]]]) -> None:
    lines = [
        r"% Auto-generated by cs336_systems/profiling_benchmarking/benchmarking_script_experiment_mixed_precision.py.",
        r"\begin{tabular}{lrrrrrrrr}",
        r"\toprule",
        r"Model & \multicolumn{2}{c}{Forward FP32} & \multicolumn{2}{c}{Forward BF16} & "
        r"\multicolumn{2}{c}{Backward FP32} & \multicolumn{2}{c}{Backward BF16} \\",
        r"\cmidrule(lr){2-3} \cmidrule(lr){4-5} \cmidrule(lr){6-7} \cmidrule(lr){8-9}",
        r" & mean (s) & sd & mean (s) & sd & mean (s) & sd & mean (s) & sd \\",
        r"\midrule",
    ]
    for config in MODEL_SIZES:
        name = config["name"]
        model_results = results[name]
        fp32_forward = format_mean_std_pair(model_results["fp32"]["forward"])
        bf16_forward = format_mean_std_pair(model_results["bf16"]["forward"])
        fp32_backward = format_mean_std_pair(model_results["fp32"]["backward"])
        bf16_backward = format_mean_std_pair(model_results["bf16"]["backward"])
        lines.append(
            f"{name} & {fp32_forward[0]} & {fp32_forward[1]} & {bf16_forward[0]} & {bf16_forward[1]} & "
            f"{fp32_backward[0]} & {fp32_backward[1]} & {bf16_backward[0]} & {bf16_backward[1]} \\\\"
        )
    lines.extend([r"\bottomrule", r"\end{tabular}"])
    RESULTS_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")


def compute_speedup(fp32_mean: float | None, bf16_mean: float | None) -> str:
    if fp32_mean is None or bf16_mean is None or bf16_mean <= 0:
        return "n/a"
    return f"{fp32_mean / bf16_mean:.2f}x"


@app.local_entrypoint()
def main():
    results = run_experiment_remote.remote()
    write_latex_table(results)
    print(f"Wrote {RESULTS_PATH.resolve()}")

    print("\nMean-time speedups (BF16 autocast vs FP32):")
    for config in MODEL_SIZES:
        name = config["name"]
        model_results = results[name]
        fp32_forward_mean = model_results["fp32"]["forward"][0]
        bf16_forward_mean = model_results["bf16"]["forward"][0]
        fp32_backward_mean = model_results["fp32"]["backward"][0]
        bf16_backward_mean = model_results["bf16"]["backward"][0]
        print(
            f"  {name}: forward {compute_speedup(fp32_forward_mean, bf16_forward_mean)}, "
            f"backward {compute_speedup(fp32_backward_mean, bf16_backward_mean)} "
            f"(fp32 {fp32_forward_mean}, {fp32_backward_mean} vs bf16 {bf16_forward_mean}, {bf16_backward_mean})"
        )
